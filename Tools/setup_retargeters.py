def read_bones(mesh):
    """-> (ordered bone list [parents precede children], {bone: parent}).
    Strategy 1: transient SkeletalMeshComponent (pure ref-skeleton data reads,
    no registration needed). Strategy 2: temp SkeletalMeshActor spawned far
    below the arena, destroyed immediately (level NEVER saved)."""
    def read_from(comp):
        setter = meth(comp, "set_skeletal_mesh_asset", "set_skeletal_mesh")
        if setter is None:
            comp.set_editor_property("skeletal_mesh_asset", mesh)
        else:
            setter(mesh)
        n = comp.get_num_bones()
        if n <= 0:
            raise RuntimeError("component reports 0 bones")
        bones = [str(comp.get_bone_name(i)) for i in range(n)]
        parents = {b: str(comp.get_parent_bone(b)) for b in bones}
        return bones, parents

    try:
        comp = unreal.new_object(unreal.SkeletalMeshComponent)
        return read_from(comp)
    except Exception as exc:
        warn("transient-component bone read failed (%s) -- spawning a temp "
             "SkeletalMeshActor instead" % exc)
    sub = unreal.get_editor_subsystem(unreal.EditorActorSubsystem)
    actor = sub.spawn_actor_from_class(
        unreal.SkeletalMeshActor, unreal.Vector(0.0, 0.0, -100000.0))
    if actor is None:
        raise RuntimeError("could not spawn a temp SkeletalMeshActor to read bones")
    try:
        comp = actor.get_editor_property("skeletal_mesh_component")
        return read_from(comp)
    finally:
        try:
            sub.destroy_actor(actor)
        except Exception:
            pass
        gc_tick()


