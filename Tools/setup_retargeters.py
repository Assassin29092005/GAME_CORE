def create_or_load_rig(rig_name, mesh, pair_name):
    """Create (or reuse) /Game/Arena/Retargeters/<rig_name> bound to mesh.
    Returns (rig, used_template: bool). Raises on hard failure."""
    rig_path = "%s/%s" % (RTG_DIR, rig_name)
    if unreal.EditorAssetLibrary.does_asset_exist(rig_path):
        rig = unreal.EditorAssetLibrary.load_asset(rig_path)
        if rig is None or not isinstance(rig, unreal.IKRigDefinition):
            raise RuntimeError("%s exists but is not an IKRigDefinition" % rig_path)
        ctrl = unreal.IKRigController.get_controller(rig)
        existing_mesh = ctrl.get_skeletal_mesh()
        if existing_mesh is None or existing_mesh.get_path_name() != mesh.get_path_name():
            raise RuntimeError(
                "%s exists but is bound to %s, not %s -- refusing to overwrite; "
                "delete it or rename the pair's rig_name"
                % (rig_path, existing_mesh.get_path_name() if existing_mesh else "None",
                   mesh.get_path_name()))
        n_chains = len(list(ctrl.get_retarget_chains()))
        if n_chains > 0:
            log("[%s] reusing existing rig %s (%d chains) -- idempotent skip"
                % (pair_name, rig_path, n_chains))
            return rig, True   # configured earlier by us/editor: trust it
        log("[%s] rig %s exists but has 0 chains -- reconfiguring it"
            % (pair_name, rig_path))
    else:
        rig = None
        creator = getattr(unreal.IKRigDefinitionFactory, "create_new_ik_rig_asset", None) \
            if hasattr(unreal, "IKRigDefinitionFactory") else None
        if creator is not None:
            rig = creator(RTG_DIR, rig_name)
        if rig is None:
            tools = unreal.AssetToolsHelpers.get_asset_tools()
            rig = tools.create_asset(rig_name, RTG_DIR, unreal.IKRigDefinition,
                                     unreal.IKRigDefinitionFactory())
        if rig is None:
            raise RuntimeError("could not create IK Rig asset %s" % rig_path)
        log("[%s] created IK Rig %s" % (pair_name, rig_path))
    gc_tick()

    ctrl = unreal.IKRigController.get_controller(rig)
    if not ctrl.set_skeletal_mesh(mesh):
        raise RuntimeError("SetSkeletalMesh(%s) failed on %s"
                           % (mesh.get_name(), rig_path))

    # THE auto-chain magic: the same template characterizer behind the
    # editor's right-click auto-retarget flow.
    used_template = False
    auto_gen = meth(ctrl, "apply_auto_generated_retarget_definition")
    if auto_gen is not None:
        try:
            used_template = bool(auto_gen())
        except Exception as exc:
            warn("[%s] ApplyAutoGeneratedRetargetDefinition raised: %s"
                 % (pair_name, exc))
    else:
        warn("[%s] apply_auto_generated_retarget_definition missing from the "
             "bindings -- going straight to the fuzzy mapper" % pair_name)

    n_chains = len(list(ctrl.get_retarget_chains()))
    if used_template and n_chains > 0:
        log("[%s] template characterization matched: %d chains on %s"
            % (pair_name, n_chains, rig_name))
        # Optional FBIK polish (goals/solver). The retargeter disables the
        # Run-IK op anyway (editor parity), so failure here is cosmetic.
        fbik = meth(ctrl, "apply_auto_fbik")
        if fbik is not None:
            try:
                fbik()
            except Exception as exc:
                warn("[%s] ApplyAutoFBIK failed (non-fatal, IK op is disabled "
                     "anyway): %s" % (pair_name, exc))
        return rig, True
    if n_chains > 0:
        warn("[%s] characterizer produced %d chains WITHOUT a template match "
             "-- keeping them (verify the table in the retargeter step)"
             % (pair_name, n_chains))
        return rig, False

    # ---- fuzzy fallback (unknown skeleton, e.g. the golem) ----
    log("[%s] no template match for %s -- building chains from bone names"
        % (pair_name, mesh.get_name()))
    bones, parents = read_bones(mesh)
    pelvis, chains = build_fuzzy_chains(bones, parents, pair_name)
    set_root = meth(ctrl, "set_retarget_root", "set_pelvis_bone")
    if set_root is None:
        raise RuntimeError("neither set_retarget_root nor set_pelvis_bone "
                           "exists on IKRigController -- API drift")
    if not set_root(pelvis):
        raise RuntimeError("SetRetargetRoot(%s) failed" % pelvis)
    made = 0
    for cn, s, e in chains:
        try:
            created = ctrl.add_retarget_chain(cn, s, e, "None")
            if str(created) not in ("", "None"):
                made += 1
            else:
                warn("[%s] chain %s (%s -> %s) rejected by the rig" % (pair_name, cn, s, e))
        except Exception as exc:
            warn("[%s] chain %s (%s -> %s) raised: %s" % (pair_name, cn, s, e, exc))
    # VERIFY by re-read (write-back paranoia rule).
    n_chains = len(list(ctrl.get_retarget_chains()))
    got_root = "?"
    get_root = meth(ctrl, "get_retarget_root", "get_pelvis_bone")
    if get_root is not None:
        try:
            got_root = str(get_root())
        except Exception:
            pass
    log("[%s] fuzzy rig result: %d/%d chains stuck, pelvis re-read=%s"
        % (pair_name, n_chains, len(chains), got_root))
    if n_chains == 0 or made == 0:
        raise RuntimeError("fuzzy chain setup produced 0 usable chains")
    return rig, False


