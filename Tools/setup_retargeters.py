def asset_class_name(asset_data):
    """Class name off an AssetData across the 5.x drift (same helper as the
    proven batch_retarget_anims.py)."""
    try:
        return str(asset_data.asset_class_path.asset_name)
    except AttributeError:
        pass
    try:
        return str(asset_data.get_editor_property("asset_class"))
    except Exception:
        return ""


def list_assets_of(folders, classes, include_regex=""):
    """[(path, AssetData)] for matching assets under the given /Game folders."""
    rx = re.compile(include_regex) if include_regex else None
    out = []
    for folder in folders:
        if not unreal.EditorAssetLibrary.does_directory_exist(folder):
            warn("anim folder does not exist: %s" % folder)
            continue
        for path in unreal.EditorAssetLibrary.list_assets(
                folder, recursive=True, include_folder=False):
            ad = unreal.EditorAssetLibrary.find_asset_data(str(path))
            if asset_class_name(ad) not in classes:
                continue
            name = str(ad.asset_name)
            if rx is not None and not rx.match(name):
                continue
            out.append((str(path), ad))
    return sorted(out, key=lambda t: t[0].lower())


def load_mesh(path, what):
    mesh = unreal.EditorAssetLibrary.load_asset(path)
    if mesh is None or not isinstance(mesh, unreal.SkeletalMesh):
        raise RuntimeError("%s is not a loadable SkeletalMesh: %s" % (what, path))
    return mesh


def skeleton_path_of(obj):
    try:
        skel = obj.get_editor_property("skeleton")
        return skel.get_path_name() if skel else ""
    except Exception:
        return ""


def resolve_source_mesh(pair):
    """Load pair['source_mesh'] and VERIFY the pack's anims actually animate
    its skeleton; on mismatch, rediscover a mesh for the dominant skeleton."""
    mesh = load_mesh(pair["source_mesh"], "source_mesh")
    if not pair["anim_folders"]:
        return mesh
    # Sample the pack's sequences and tally their skeletons (registry tag =
    # cheap; no loading).
    tally = {}
    sample = list_assets_of(pair["anim_folders"], ("AnimSequence",),
                            pair.get("include_regex", ""))[:60]
    for _, ad in sample:
        try:
            skel_tag = str(ad.get_tag_value("Skeleton") or "")
        except Exception:
            skel_tag = ""
        if skel_tag:
            tally[skel_tag] = tally.get(skel_tag, 0) + 1
    if not tally:
        warn("[%s] no AnimSequences found to verify the source skeleton "
             "against -- trusting %s" % (pair["name"], pair["source_mesh"]))
        return mesh
    dominant = max(tally, key=tally.get)
    mesh_skel = skeleton_path_of(mesh)
    if mesh_skel and mesh_skel in dominant:
        log("[%s] source mesh skeleton verified against %d pack anims (%s)"
            % (pair["name"], sum(tally.values()), mesh_skel))
        return mesh
    warn("[%s] source mesh skeleton MISMATCH: mesh=%s pack-dominant=%s -- "
         "rediscovering a compatible SkeletalMesh" % (pair["name"], mesh_skel, dominant))
    # Find a SkeletalMesh whose registry Skeleton tag matches the dominant
    # skeleton: pack folders first, then /Game-wide.
    roots = [f.rsplit("/", 1)[0] for f in pair["anim_folders"]] + ["/Game"]
    for root in roots:
        for path in unreal.EditorAssetLibrary.list_assets(root, recursive=True,
                                                          include_folder=False):
            ad = unreal.EditorAssetLibrary.find_asset_data(str(path))
            if asset_class_name(ad) != "SkeletalMesh":
                continue
            try:
                if str(ad.get_tag_value("Skeleton") or "") == dominant:
                    m = load_mesh(str(path).split(".")[0], "rediscovered source mesh")
                    warn("[%s] using rediscovered source mesh %s" % (pair["name"], path))
                    return m
            except Exception:
                continue
    raise RuntimeError("no SkeletalMesh found for the pack's skeleton %s" % dominant)


