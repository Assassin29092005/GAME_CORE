def do_pair(pair, caps):
    name = pair["name"]

    # -- meshes --
    try:
        src_mesh = resolve_source_mesh(pair)
        tgt_mesh = load_mesh(pair["target_mesh"], "target_mesh")
        record("%s meshes" % name, "PASS",
               "%s -> %s" % (src_mesh.get_name(), tgt_mesh.get_name()))
    except Exception as exc:
        record("%s meshes" % name, "FAIL", str(exc))
        print_manual(pair, "Mesh resolution failed: %s." % exc)
        return

    # -- IK rigs --
    if not (caps["rig_class"] and caps["rig_ctrl"]):
        record("%s ik rigs" % name, "FAIL", "IKRig python surface missing")
        print_manual(pair, "IKRigDefinition/IKRigController not in the python "
                           "bindings (IK Rig plugin off?).")
        return
    try:
        src_rig, src_template = create_or_load_rig(
            pair["source_rig_name"], src_mesh, name)
        tgt_rig, tgt_template = create_or_load_rig(
            pair["target_rig_name"], tgt_mesh, name)
        record("%s ik rigs" % name, "PASS",
               "src=%s(template=%s) tgt=%s(template=%s)"
               % (pair["source_rig_name"], src_template,
                  pair["target_rig_name"], tgt_template))
    except Exception as exc:
        record("%s ik rigs" % name, "FAIL", str(exc))
        traceback.print_exc()
        print_manual(pair, "IK Rig creation failed: %s." % exc)
        return

    # -- retargeter --
    if not (caps["rtg_class"] and caps["rtg_ctrl"] and caps["src_or_tgt"]):
        record("%s retargeter" % name, "FAIL", "IKRetargeter python surface missing")
        print_manual(pair, "IKRetargeter/IKRetargeterController not in the "
                           "python bindings.")
        return
    try:
        rtg, configured = create_or_load_retargeter(
            pair, src_rig, tgt_rig, src_mesh, tgt_mesh,
            both_template=(src_template and tgt_template))
        rc = unreal.IKRetargeterController.get_controller(rtg)
        mapped, total, rows = count_mapped_chains(rc, tgt_rig)
        log("[%s] CHAIN MAPPING (target <- source):" % name)
        for cn, srcn in rows:
            log("  %-20s <- %s" % (cn, srcn))
        if total > 0 and mapped == 0:
            record("%s retargeter" % name, "FAIL",
                   "0/%d target chains mapped after AutoMapChains" % total)
            print_manual(pair, "AutoMapChains produced no mappings -- open "
                                "%s and map chains by hand." % pair["retargeter"])
            return
        record("%s retargeter" % name, "PASS",
               "%s (%d/%d chains mapped%s)"
               % (pair["retargeter"], mapped, total,
                  ", reconfigured" if configured else ", reused"))
    except Exception as exc:
        record("%s retargeter" % name, "FAIL", str(exc))
        traceback.print_exc()
        print_manual(pair, "Retargeter wiring failed: %s." % exc)
        return

    # -- save (rigs + retargeter) --
    try:
        for asset in (src_rig, tgt_rig, rtg):
            force_save_asset(asset)
        record("%s save" % name, "PASS", "rigs + retargeter force-saved, "
                                         "mtime-verified")
    except Exception as exc:
        record("%s save" % name, "FAIL", str(exc))
        return

    # -- batch --
    if not DO_BATCH:
        record("%s batch" % name, "SKIP", "DO_BATCH=False")
        return
    if not caps["batch"]:
        record("%s batch" % name, "FAIL",
               "IKRetargetBatchOperation.duplicate_and_retarget missing")
        print_manual(pair, "Batch API missing -- run Tools/"
                           "batch_retarget_anims.py from the editor instead.")
        return
    try:
        passed, failed, skipped = run_batch(pair, rtg, src_mesh, tgt_mesh)
        status = "PASS" if failed == 0 else ("FAIL" if passed == 0 else "PASS")
        record("%s batch" % name, status,
               "%d retargeted, %d failed, %d skipped (already done) -> %s"
               % (passed, failed, skipped, pair["out_folder"]))
    except Exception as exc:
        record("%s batch" % name, "FAIL", str(exc))
        traceback.print_exc()
    gc_tick(force=True)


# ---------------------------------------------------------------------------
# Main
# ---------------------------------------------------------------------------

def main():
    log("=== setup_retargeters: %d pair(s), DO_BATCH=%s ===" % (len(PAIRS), DO_BATCH))
    caps = preflight()
    if not (caps["rig_class"] or caps["rtg_class"]):
        err("IK Rig plugin surface entirely absent -- enable Edit -> Plugins "
            "-> 'IK Rig' and re-run. Printing manual recipes for all pairs.")
        for pair in PAIRS:
            print_manual(pair, "IK Rig plugin is disabled.")
    else:
        if not unreal.EditorAssetLibrary.does_directory_exist(RTG_DIR):
            unreal.EditorAssetLibrary.make_directory(RTG_DIR)
        for pair in PAIRS:
            if ONLY_PAIRS and pair["name"] not in ONLY_PAIRS:
                record("%s (pair)" % pair["name"], "SKIP",
                       "not in SETUP_RTG_PAIRS=%s" % ",".join(ONLY_PAIRS))
                continue
            log("--- PAIR %s ---" % pair["name"])
            try:
                do_pair(pair, caps)
            except Exception as exc:   # per-pair isolation: never abort the run
                record("%s (pair)" % pair["name"], "FAIL", str(exc))
                traceback.print_exc()
            gc_tick(force=True)

    log("=" * 60)
    log("SETUP-RETARGETERS SUMMARY")
    log("=" * 60)
    n_fail = 0
    for label, status, detail in STEP_RESULTS:
        line = "%-5s %-28s %s" % (status, label, detail)
        (warn if status == "FAIL" else log)(line)
        n_fail += status == "FAIL"
    for note in MANUAL_NOTES:
        warn(note)
    if n_fail:
        warn("%d step(s) FAILED -- see above. Everything that passed is "
             "saved and re-runnable (idempotent)." % n_fail)
    else:
        log("All steps passed. Retargeters live in %s; batch outputs in the "
            "per-pair folders. Reminder: batch outputs are per-character "
            "copies -- never share montages across characters (CLAUDE.md)."
            % RTG_DIR)


main()
