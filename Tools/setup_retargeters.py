# Fuzzy chain mapping (unknown skeletons, e.g. Stone Golem)
# ---------------------------------------------------------------------------

_PELVIS_RX = re.compile(r"pelvis|hips|\bhip\b|waist|\bcog\b")
_SPINE_RX = re.compile(r"spine|chest|torso|\bbody\b")
_NECK_RX = re.compile(r"neck")
_HEAD_RX = re.compile(r"head")
_HAND_RX = re.compile(r"hand|wrist|palm")
_FOOT_RX = re.compile(r"foot|ankle")
_TOE_RX = re.compile(r"\btoe|ball")
_CLAV_RX = re.compile(r"clavicle|collar|scap|shoulder")


def side_of(name):
    n = name.lower()
    toks = re.split(r"[^a-z0-9]+", n)
    if "l" in toks or "left" in toks or n.endswith("_l") or n.startswith("l_") or "left" in n:
        return "L"
    if "r" in toks or "right" in toks or n.endswith("_r") or n.startswith("r_") or "right" in n:
        return "R"
    return ""


def _first(bones, rx, side=None):
    for b in bones:
        if rx.search(b.lower()) and (side is None or side_of(b) == side):
            return b
    return None


def _walk_up(bone, parents, stop_rx):
    """Path [bone, parent, ...] ending just BELOW the first ancestor matching
    stop_rx (or the root). Returns the path list."""
    path = [bone]
    while True:
        p = parents.get(path[-1], "None")
        if p in ("", "None") or stop_rx.search(p.lower()):
            return path
        path.append(p)


def build_fuzzy_chains(bones, parents, pair_name):
    """-> (pelvis, [(chain_name, start_bone, end_bone)]). Name+topology based:
    hand/foot/head/pelvis are the most conserved names across rigs; chain
    starts are found by walking UP the real hierarchy, not by name guessing."""
    pelvis = _first(bones, _PELVIS_RX)
    chains = []
    if pelvis is None:
        raise RuntimeError("no pelvis-like bone (pelvis|hips|hip|waist|cog) "
                           "among: %s" % ", ".join(bones[:20]))
    spine_bones = [b for b in bones if _SPINE_RX.search(b.lower()) and side_of(b) == ""]
    if spine_bones:
        chains.append((CN_SPINE, spine_bones[0], spine_bones[-1]))
    neck_bones = [b for b in bones if _NECK_RX.search(b.lower())]
    if neck_bones:
        chains.append((CN_NECK, neck_bones[0], neck_bones[-1]))
    head = _first(bones, _HEAD_RX)
    if head:
        chains.append((CN_HEAD, head, head))
    boundary_rx = re.compile("%s|%s" % (_SPINE_RX.pattern, _PELVIS_RX.pattern))
    for side in ("L", "R"):
        hand = _first(bones, _HAND_RX, side)
        if hand:
            path = _walk_up(hand, parents, boundary_rx)
            top = path[-1]
            if _CLAV_RX.search(top.lower()) and len(path) > 1:
                chains.append((CN_CLAV[side], top, top))
                chains.append((CN_ARM[side], path[-2], hand))
            else:
                chains.append((CN_ARM[side], top, hand))
        foot = _first(bones, _FOOT_RX, side)
        if foot:
            toe = _first(bones, _TOE_RX, side)
            path = _walk_up(foot, parents, _PELVIS_RX)
            chains.append((CN_LEG[side], path[-1], toe if toe else foot))
    # Loud audit table.
    log("[%s] FUZZY BONE MAP (pelvis=%s):" % (pair_name, pelvis))
    log("  %-16s %-28s %s" % ("chain", "start", "end"))
    used = {pelvis}
    for cn, s, e in chains:
        log("  %-16s %-28s %s" % (cn, s, e))
        used.update((s, e))
    unmapped = [b for b in bones if b not in used]
    log("[%s] %d bones total, %d anchored to chains; unmapped (intermediate/"
        "extra): %s%s" % (pair_name, len(bones), len(used), ", ".join(unmapped[:40]),
                          " ..." if len(unmapped) > 40 else ""))
    # Fail LOUDLY on missing essentials (pelvis is checked above): a torso- or
    # limb-less chain set retargets to visibly broken animation. Head/Neck/
    # Clavicle stay optional.
    essential = (CN_SPINE, CN_LEG["L"], CN_LEG["R"], CN_ARM["L"], CN_ARM["R"])
    have = {cn for cn, _s, _e in chains}
    missing_ess = [cn for cn in essential if cn not in have]
    if missing_ess:
        raise RuntimeError(
            "fuzzy mapper missing essential chain(s): %s -- refusing to build "
            "a broken retarget mapping; fix the bone-name regexes or author "
            "the IK Rig by hand (see the table above)" % ", ".join(missing_ess))
    return pelvis, chains


