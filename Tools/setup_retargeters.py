def meth(obj, *names):
    """First callable attribute among candidate python names, else None."""
    for n in names:
        fn = getattr(obj, n, None)
        if callable(fn):
            return fn
    return None


def enum_member(enum_name, *members):
    e = getattr(unreal, enum_name, None)
    if e is None:
        return None
    for m in members:
        v = getattr(e, m, None)
        if v is not None:
            return v
    return None


