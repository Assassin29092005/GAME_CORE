SRC = enum_member("RetargetSourceOrTarget", "SOURCE")
TGT = enum_member("RetargetSourceOrTarget", "TARGET")


def rig_path_of(rig):
    return rig.get_path_name().split(".")[0] if rig else ""


def create_or_load_retargeter(pair, src_rig, tgt_rig, src_mesh, tgt_mesh,
                              both_template):
    rtg_path = pair["retargeter"]
    name = rtg_path.rsplit("/", 1)[1]
    rtg, needs_config = None, True
    if unreal.EditorAssetLibrary.does_asset_exist(rtg_path):
        rtg = unreal.EditorAssetLibrary.load_asset(rtg_path)
        if rtg is None or not isinstance(rtg, unreal.IKRetargeter):
            raise RuntimeError("%s exists but is not an IKRetargeter" % rtg_path)
        rc = unreal.IKRetargeterController.get_controller(rtg)
        cur_src = rc.get_ik_rig(SRC)
        cur_tgt = rc.get_ik_rig(TGT)
        if (not FORCE_RECONFIGURE
                and rig_path_of(cur_src) == rig_path_of(src_rig)
                and rig_path_of(cur_tgt) == rig_path_of(tgt_rig)
                and count_mapped_chains(rc, tgt_rig)[0] > 0):
            log("[%s] reusing existing retargeter %s (rigs match, chains "
                "mapped) -- idempotent skip" % (pair["name"], rtg_path))
            return rtg, False
        warn("[%s] %s exists but needs (re)wiring -- reconfiguring"
             % (pair["name"], rtg_path))
    else:
        tools = unreal.AssetToolsHelpers.get_asset_tools()
        rtg = tools.create_asset(name, RTG_DIR, unreal.IKRetargeter,
                                 unreal.IKRetargetFactory())
        if rtg is None:
            raise RuntimeError("could not create IK Retargeter %s" % rtg_path)
        log("[%s] created IK Retargeter %s" % (pair["name"], rtg_path))
    gc_tick()

    # ---- the editor auto-flow recipe (FProceduralRetargetAssets parity) ----
    rc = unreal.IKRetargeterController.get_controller(rtg)
    rc.set_ik_rig(SRC, src_rig)
    rc.set_ik_rig(TGT, tgt_rig)

    # 5.8 op stack. NOTE (from the engine source): ops must exist BEFORE the
    # retarget-pose work; SetIKRig(Target) does NOT auto-assign into ops.
    if meth(rc, "remove_all_ops") and meth(rc, "add_default_ops"):
        rc.remove_all_ops()
        rc.add_default_ops()
        assign_all = meth(rc, "assign_ik_rig_to_all_ops")
        if assign_all is not None:
            try:  # belt & braces: some ops keep their own target-rig slot
                assign_all(TGT, tgt_rig)
            except Exception as exc:
                warn("[%s] AssignIKRigToAllOps failed (default ops usually "
                     "self-assign): %s" % (pair["name"], exc))
    else:
        warn("[%s] op-stack API missing (pre-5.7 style retargeter?) -- "
             "relying on asset-level chain settings" % pair["name"])

    # Chain mapping: Exact for template rigs (editor default -- fuzzy can map
    # toes to fingers), Fuzzy when either side came from the fuzzy mapper.
    map_mode = enum_member("AutoMapChainType", "EXACT") if both_template \
        else enum_member("AutoMapChainType", "FUZZY")
    if map_mode is None:
        raise RuntimeError("unreal.AutoMapChainType missing -- API drift")
    rc.auto_map_chains(map_mode, True)   # op_name omitted -> ALL ops

    # Regenerate + auto-align the target retarget pose (A- vs T-pose fix).
    try:
        pose = rc.get_current_retarget_pose_name(TGT)
        rc.reset_retarget_pose(pose, [], TGT)
        if AUTO_ALIGN and pair.get("auto_align", True):
            align = meth(rc, "auto_align_all_bones")
            if align is not None:
                try:
                    align(TGT)
                except TypeError:
                    m = enum_member("RetargetAutoAlignMethod", "CHAIN_TO_CHAIN")
                    align(TGT, m)
    except Exception as exc:
        warn("[%s] retarget-pose regen/auto-align failed (fix in the "
             "retargeter editor if the output looks twisted): %s"
             % (pair["name"], exc))

    # Disable the Run-IK op -- editor auto-flow parity ("auto-IK is not yet
    # robust"); FK chains + pelvis motion carry the retarget.
    try:
        n_ops = rc.get_num_retarget_ops()
        for i in range(n_ops):
            opc = None
            get_opc = meth(rc, "get_op_controller")
            if get_opc is not None:
                try:
                    opc = get_opc(i)
                except Exception:
                    opc = None
            label = type(opc).__name__ if opc is not None else str(rc.get_op_name(i))
            if "runikrig" in label.lower().replace(" ", "") or "runik" in label.lower():
                rc.set_retarget_op_enabled(i, False)
                log("[%s] disabled op %d (%s)" % (pair["name"], i, label))
    except Exception as exc:
        warn("[%s] could not disable the Run-IK op (harmless if FBIK was "
             "never added): %s" % (pair["name"], exc))

    # Preview meshes: batch_retarget_anims.py-style consumers read these.
    try:
        rc.set_preview_mesh(SRC, src_mesh)
        rc.set_preview_mesh(TGT, tgt_mesh)
    except Exception as exc:
        warn("[%s] SetPreviewMesh failed: %s" % (pair["name"], exc))
    return rtg, True


def count_mapped_chains(rc, tgt_rig):
    """(mapped, total, [(target_chain, source_chain)]) read back from the
    retargeter -- the verify-every-questionable-write rule."""
    rows, mapped = [], 0
    try:
        tgt_ctrl = unreal.IKRigController.get_controller(tgt_rig)
        for chain in tgt_ctrl.get_retarget_chains():
            try:
                cn = str(chain.get_editor_property("chain_name"))
            except Exception:
                continue
            try:
                src = str(rc.get_source_chain(cn))
            except Exception:
                src = "?"
            rows.append((cn, src))
            if src not in ("", "None", "?"):
                mapped += 1
    except Exception as exc:
        warn("chain-mapping read-back failed: %s" % exc)
    return mapped, len(rows), rows


