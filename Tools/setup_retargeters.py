def gc_tick(force=False):
    _OP_COUNT[0] += 1
    if force or _OP_COUNT[0] % GC_EVERY == 0:
        try:
            unreal.SystemLibrary.collect_garbage()
        except Exception:
            pass


def assert_allowed(asset_path):
    if not any(asset_path.startswith(p) or asset_path + "/" == p
               for p in ALLOWED_PREFIXES):
        raise RuntimeError("REFUSING to write outside owned folders: %s" % asset_path)


def force_save_asset(asset):
    """Proven force-save: mark dirty -> save(only_if_is_dirty=False) -> verify
    the .uasset mtime advanced on disk (dirty-gated saves silently wrote
    NOTHING earlier in this project)."""
    pkg_name = asset.get_outer().get_name()
    assert_allowed(pkg_name)
    try:
        asset.get_outer().mark_package_dirty()
    except Exception:
        pass
    disk_path = None
    if pkg_name.startswith("/Game/"):
        disk_path = os.path.join(
            unreal.Paths.project_content_dir(), pkg_name[len("/Game/"):] + ".uasset")
    before = os.path.getmtime(disk_path) if disk_path and os.path.isfile(disk_path) else None
    if not unreal.EditorAssetLibrary.save_loaded_asset(asset, only_if_is_dirty=False):
        raise RuntimeError("save_loaded_asset failed for %s" % asset.get_path_name())
    if before is not None:
        after = os.path.getmtime(disk_path)
        if after <= before:
            raise RuntimeError("save reported success but %s was NOT rewritten on disk"
                               % disk_path)
    gc_tick()


