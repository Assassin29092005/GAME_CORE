def expected_output_name(pair, src_name):
    n = src_name
    if pair["search"]:
        n = n.replace(pair["search"], pair["replace"])
    return pair["prefix"] + n


def run_batch(pair, rtg, src_mesh, tgt_mesh):
    if not pair["prefix"]:
        raise RuntimeError("prefix must be non-empty (pre-5.8 fallback "
                           "duplicates land NEXT TO sources; empty prefix "
                           "would collide with the originals)")
    candidates = list_assets_of(pair["anim_folders"], pair["classes"],
                                pair.get("include_regex", ""))
    out_folder = pair["out_folder"]
    to_retarget, skipped = [], 0
    for path, ad in candidates:
        if path.startswith(out_folder + "/"):
            continue
        name = str(ad.asset_name)
        if name.startswith(pair["prefix"]):
            skipped += 1
            continue   # leftover output from a prior failed move
        if unreal.EditorAssetLibrary.does_asset_exist(
                "%s/%s" % (out_folder, expected_output_name(pair, name))):
            skipped += 1
            continue
        to_retarget.append(ad)
    if not to_retarget:
        return 0, 0, skipped
    # Flat-output name-collision guard (same rationale as the proven script).
    counts = {}
    for ad in to_retarget:
        n = expected_output_name(pair, str(ad.asset_name))
        counts[n] = counts.get(n, 0) + 1
    dupes = sorted(n for n, c in counts.items() if c > 1)
    if dupes:
        raise RuntimeError("output name collision(s) into flat %s: %s -- "
                           "retarget subfolders separately or change the "
                           "prefix" % (out_folder, ", ".join(dupes[:8])))
    if not unreal.EditorAssetLibrary.does_directory_exist(out_folder):
        unreal.EditorAssetLibrary.make_directory(out_folder)
    log("[%s] batch retargeting %d asset(s): %s -> %s via %s ..."
        % (pair["name"], len(to_retarget), src_mesh.get_name(),
           tgt_mesh.get_name(), pair["retargeter"]))
    created, moved_needed = None, False
    # Primary (5.8+): RunBatchRetarget(FIKRetargetBatchOperationInputs) --
    # DuplicateAndRetarget is UE_DEPRECATED(5.8) in the engine source.
    if hasattr(unreal.IKRetargetBatchOperation, "run_batch_retarget") \
            and hasattr(unreal, "IKRetargetBatchOperationInputs"):
        try:
            inputs = unreal.IKRetargetBatchOperationInputs()
            inputs.set_editor_property("assets_to_retarget", to_retarget)
            inputs.set_editor_property("source_mesh", src_mesh)
            inputs.set_editor_property("target_mesh", tgt_mesh)
            inputs.set_editor_property("ik_retarget_asset", rtg)
            inputs.set_editor_property("search", pair["search"])
            inputs.set_editor_property("replace", pair["replace"])
            inputs.set_editor_property("prefix", pair["prefix"])
            inputs.set_editor_property("target_path", out_folder)
            created = unreal.IKRetargetBatchOperation.run_batch_retarget(inputs)
        except Exception as exc:
            warn("[%s] RunBatchRetarget path failed (%s) -- falling back to "
                 "duplicate_and_retarget" % (pair["name"], exc))
            created = None
    if created is None:
        # Fallback: first 8 args positional (stable 5.2-5.8); target_path is
        # the 5.8 destination kwarg -- TypeError means older bindings, fall
        # back to duplicate-next-to-source + move (the proven handling from
        # Tools/batch_retarget_anims.py).
        try:
            created = unreal.IKRetargetBatchOperation.duplicate_and_retarget(
                to_retarget, src_mesh, tgt_mesh, rtg,
                pair["search"], pair["replace"], pair["prefix"], "",
                target_path=out_folder)
        except TypeError:
            warn("[%s] pre-5.8 batch signature (no target_path) -- will move "
                 "outputs into %s" % (pair["name"], out_folder))
            created = unreal.IKRetargetBatchOperation.duplicate_and_retarget(
                to_retarget, src_mesh, tgt_mesh, rtg,
                pair["search"], pair["replace"], pair["prefix"], "")
            moved_needed = True
    created_by_name = {}
    for ad in list(created or []):
        created_by_name.setdefault(str(ad.asset_name), ad)
    passed, failed = 0, 0
    for ad in to_retarget:
        want = expected_output_name(pair, str(ad.asset_name))
        got = created_by_name.get(want)
        if got is None:
            warn("[%s] batch FAIL: %s -> no output named %s (see retargeter "
                 "chain errors above)" % (pair["name"], ad.asset_name, want))
            failed += 1
            continue
        if moved_needed:
            old_path = str(got.package_name)
            dest = "%s/%s" % (out_folder, want)
            if old_path != dest and not unreal.EditorAssetLibrary.rename_asset(old_path, dest):
                warn("[%s] retargeted OK but move failed: %s -> %s (usable "
                     "where it is; move manually)" % (pair["name"], old_path, dest))
        passed += 1
    unreal.EditorAssetLibrary.save_directory(out_folder, only_if_is_dirty=True)
    gc_tick(force=True)
    return passed, failed, skipped


